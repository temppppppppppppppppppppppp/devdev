WUXIA_AMENDMENTS = """
### Wuxia-Specific Rules

Amendment W1: 무공 위계 준수
- 후천 경지는 선천 비기를 사용할 수 없음
- 내공 수치가 기술의 요구치보다 낮으면 사용 불가

Amendment W2: 강호 예법
- 무림맹주에게 존댓말 필수
- 사파/정파 구분 명확

Amendment W3: 무공 묘사
- 초식 이름 명시
- 내공 운용 과정 서술
"""

HUNTER_AMENDMENTS = """
### Hunter-Specific Rules

Amendment H1: 게이트 등급 준수
- E급 헌터는 D급 게이트 입장 불가
- 게이트 등급에 맞는 몬스터 출현

Amendment H2: 스킬 시스템
- 미획득 스킬 사용 불가
- 스킬 쿨타임 준수

Amendment H3: 각성자 설정
- 각성 전 능력 사용 불가
- 각성 조건 명확히
"""

INVESTMENT_AMENDMENTS = """
### Investment-Specific Rules

Amendment I1: 재무 현실성
- 투자 수익률의 현실성 (연 100% 이상은 근거 필요)
- 자금 출처 명확

Amendment I2: 시장 법칙
- 주가 조작 시 증거 제시
- 공매도/선물 등 정확한 용어

Amendment I3: 인맥 관리
- 인맥 효과의 합리성
- 정보 획득 경로 명시
"""


def get_constitution_for_genre(genre: str) -> str:
    """장르별 품질 헌법 반환"""
    base = QUALITY_CONSTITUTION

    if genre == 'wuxia':
        return base + "\n\n" + WUXIA_AMENDMENTS
    elif genre == 'hunter':
        return base + "\n\n" + HUNTER_AMENDMENTS
    elif genre == 'investment':
        return base + "\n\n" + INVESTMENT_AMENDMENTS
    else:
        return base
