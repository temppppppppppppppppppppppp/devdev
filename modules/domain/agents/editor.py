import json
import re
from .base_agent import BaseAgent

# =================================================================
# V25 상업 웹소설 최종 교정(Editor) 프롬프트
# =================================================================

EDITOR_POLISH_PROMPT_V25 = """
당신은 카카오페이지와 네이버 시리즈에서 수많은 히트작을 배출한 [V25 수석 편집장]입니다.
당신의 임무는 작가가 집필한 원고에서 '느끼함'을 걷어내고, '장르적 금기'를 수정하여 바로 연재 가능한 상태로 만드는 것입니다.

### 🎯 V25 교정 지침 (The Golden Rules)
1. **수치 한글화 (Critical)**: 
   - 모든 아라비아 숫자를 무협의 결에 맞게 한글로 치환하십시오. (예: 3일 -> 사흘/삼 일, 10명 -> 열 명)
2. **느끼함 제거 (Degreasing)**: 
   - 과도한 형용사, 오글거리는 수식어, 불필요하게 긴 심리 묘사를 삭제하거나 담백한 단문으로 교체하십시오.
3. **플랫폼 톤 최적화**: 
   - [카카오 스타일]: 문장을 더 짧게 치고, 줄 바꿈을 늘려 스마트폰 가독성을 극대화하십시오.
   - [시리즈 스타일]: 문장의 비장미는 살리되, 문어체와 구어체의 조화를 점검하십시오.
4. **페르소나 동기화**: 
   - [인물 페르소나 라이브러리]를 참고하여, 각 문파와 인물의 말투(구어)가 설정과 일치하는지 확인하십시오.
5. **금기어 삭제**: 
   - '시스템', '스탯', 'HUD', '퀘스트' 등 현대 게임 용어나 판타지 용어가 섞였다면 즉시 무협 용어로 순화하십시오.
6. **서술어미 통일 (Strict Ending)**:
   - 서술문(지문)은 반드시 **'~다.'**로 끝나야 합니다.
   - **금지 어미**: '~니라', '~도다', '~노라', '~인가', '~나보다' 등 고어체나 구어체 서술을 절대 금지하고, 무조건 객관적인 평서문('~였다', '~했다')으로 고치십시오.

### ⚠️ 주의 사항
- 서사의 줄거리나 사건의 결과는 절대 바꾸지 마십시오. 오직 '문체'와 '말투', '규칙'만 교정합니다.
- 사족이나 인사말 없이 오직 **교정된 소설 본문**만 출력하십시오.
"""

class Editor(BaseAgent):
    """[V25 Persona Editor] 상업적 가독성 최적화 및 장르 규칙 최종 집행자"""

    def polish_manuscript_v25(self, ep_num, draft, persona_library, style_guide):
        """[Stage 4] 5,500자 원고의 톤앤매너 및 장르 규칙 최종 교정"""
        
        # 1. 스타일 분석 (카카오 여부 확인)
        is_kakao = "카카오" in style_guide
        platform_goal = "카카오 (단문/가독성 올인)" if is_kakao else "네이버 시리즈 (비장미/감성선)"

        prompt = f"""
{EDITOR_POLISH_PROMPT_V25}

### [📋 교정 가이드]
- **현재 회차**: 제 {ep_num}화
- **목표 플랫폼 톤**: {platform_goal}
- **인물 페르소나**: {json.dumps(persona_library, ensure_ascii=False, indent=2)}

### [📝 교정 대상 원고]
{draft}

[Output] 위 지침에 따라 완벽하게 교정된 제 {ep_num}화 최종 원고 전문을 출력하라.
"""
        # 교정의 정밀도를 위해 낮은 온도(0.3) 설정
        return self.ask(prompt, temperature=0.3)